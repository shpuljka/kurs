#!/usr/bin/env python3
"""Import circle-flags (https://github.com/HatScripts/circle-flags, MIT) as Android vector drawables.

Usage:
    # ISO 4217 codes as the JVM knows them (same list the app filters by):
    jshell -q <<< 'java.util.Currency.getAvailableCurrencies().forEach(c -> System.out.println(c.getCurrencyCode()));' > codes.txt
    python3 tools/import_flags.py <circle-flags>/flags codes.txt

Writes app/src/main/res/drawable/flag_<cc>.xml for every flag a currency needs and
app/src/main/java/io/github/shpuljka/kurs/ui/Flags.kt mapping currency code -> drawable.
The circular mask is dropped: the app clips flags to a circle itself.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"
KOTLIN = ROOT / "app/src/main/java/io/github/shpuljka/kurs/ui/Flags.kt"
NS = "{http://www.w3.org/2000/svg}"

# Currencies whose issuer is not "first two letters of the code".
SPECIAL = {"EUR": "european_union"}


def color(value: str) -> str:
    value = value.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        value = "#" + "".join(ch * 2 for ch in value[1:])
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise ValueError(f"unsupported fill {value!r}")
    return value.upper()


def num(value: str) -> float:
    return float(value)


def fmt(n: float) -> str:
    return f"{n:.3f}".rstrip("0").rstrip(".")


def ellipse_path(cx: float, cy: float, rx: float, ry: float) -> str:
    return (f"M{fmt(cx - rx)},{fmt(cy)}"
            f"a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(2 * rx)},0"
            f"a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(-2 * rx)},0z")


def rect_path(el) -> str:
    x, y = num(el.get("x", "0")), num(el.get("y", "0"))
    w, h = num(el.get("width")), num(el.get("height"))
    rx = el.get("rx") or el.get("ry")
    ry = el.get("ry") or el.get("rx")
    if not rx:
        return f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z"
    rx, ry = min(num(rx), w / 2), min(num(ry), h / 2)
    arc = lambda dx, dy: f"a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(dx)},{fmt(dy)}"
    return (f"M{fmt(x + rx)},{fmt(y)}h{fmt(w - 2 * rx)}{arc(rx, ry)}v{fmt(h - 2 * ry)}{arc(-rx, ry)}"
            f"h{fmt(-(w - 2 * rx))}{arc(-rx, -ry)}v{fmt(-(h - 2 * ry))}{arc(rx, -ry)}z")


def shapes(el):
    """Yields (fill, pathData) for every drawable element, skipping <mask> definitions."""
    for child in el:
        tag = child.tag.removeprefix(NS)
        if tag == "mask":
            continue
        if tag == "g":
            if set(child.attrib) - {"mask"}:
                raise ValueError(f"unsupported <g> attributes {child.attrib}")
            yield from shapes(child)
            continue
        extra = set(child.attrib) - {"fill", "d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height"}
        if extra:
            raise ValueError(f"unsupported attributes {extra} on <{tag}>")
        fill = color(child.get("fill", "#000"))
        if tag == "path":
            yield fill, child.get("d")
        elif tag == "circle":
            r = num(child.get("r"))
            yield fill, ellipse_path(num(child.get("cx", "0")), num(child.get("cy", "0")), r, r)
        elif tag == "ellipse":
            yield fill, ellipse_path(num(child.get("cx", "0")), num(child.get("cy", "0")),
                                     num(child.get("rx")), num(child.get("ry")))
        elif tag == "rect":
            yield fill, rect_path(child)
        else:
            raise ValueError(f"unsupported element <{tag}>")


def vector(svg: Path) -> str:
    root = ET.parse(svg).getroot()
    if root.get("viewBox") != "0 0 512 512":
        raise ValueError(f"unexpected viewBox {root.get('viewBox')}")
    paths = "\n".join(
        f'    <path android:fillColor="{fill}" android:pathData="{d}" />' for fill, d in shapes(root)
    )
    return (
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        f"<!-- {svg.name} from circle-flags (MIT), generated by tools/import_flags.py -->\n"
        "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
        "    android:width=\"48dp\"\n"
        "    android:height=\"48dp\"\n"
        "    android:viewportWidth=\"512\"\n"
        "    android:viewportHeight=\"512\">\n"
        f"{paths}\n"
        "</vector>\n"
    )


def main(flags_dir: str, codes_file: str) -> None:
    flags = Path(flags_dir)
    codes = sorted({c.strip() for c in Path(codes_file).read_text().split() if re.fullmatch(r"[A-Z]{3}", c.strip())})
    mapping: dict[str, str] = {}
    for code in codes:
        name = SPECIAL.get(code, code[:2].lower())
        if (flags / f"{name}.svg").exists():
            mapping[code] = name

    # Convert everything first: an unsupported SVG must not leave the drawables half-regenerated.
    resource, converted = {}, {}
    for name in sorted(set(mapping.values())):
        res_name = "flag_" + ("eu" if name == "european_union" else name)
        try:
            converted[res_name] = vector(flags / f"{name}.svg")
        except ValueError as e:
            sys.exit(f"{name}.svg: {e} (nothing was changed)")
        resource[name] = res_name

    for old in RES.glob("flag_*.xml"):
        old.unlink()
    for res_name, xml in converted.items():
        (RES / f"{res_name}.xml").write_text(xml)

    entries = "\n".join(f'    "{code}" to R.drawable.{resource[name]},' for code, name in sorted(mapping.items()))
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text(
        "// Generated by tools/import_flags.py — do not edit.\n"
        "package io.github.shpuljka.kurs.ui\n\n"
        "import io.github.shpuljka.kurs.R\n\n"
        "/** Currency code -> circle flag of the issuer (circle-flags, MIT). */\n"
        "val CURRENCY_FLAGS: Map<String, Int> = mapOf(\n"
        f"{entries}\n"
        ")\n"
    )
    print(f"{len(resource)} flags for {len(mapping)} currencies; no flag: {sorted(set(codes) - set(mapping))}")


if __name__ == "__main__":
    main(*sys.argv[1:])
